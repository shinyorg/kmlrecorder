#if PLATFORM
using System.Text.Json.Serialization;
using Shiny.DocumentDb;
using Shiny.DocumentDb.Sqlite;
using SkiaSharp.Views.Maui.Controls.Hosting;
using ShinyKmlRecorder.Services.Impl;

namespace ShinyKmlRecorder;


public static class MauiProgram
{
    public static MauiApp CreateMauiApp()
    {
        var builder = MauiApp
            .CreateBuilder()
            .UseMauiApp<App>()
            .UseShiny()
            .UseShinyShell(x => x
                .AddGeneratedMaps()
                .UseUxDiversDialogs()
            )
            .AddAppSupport()
            .UseShinyControls(x => x.AddDefaultMauiControlFeedback())
            .UseSkiaSharp() // Mapsui renders the trip map with SkiaSharp
            .ConfigureFonts(fonts =>
            {
                fonts.AddFont("OpenSans-Regular.ttf", "OpenSansRegular");
                fonts.AddFont("OpenSans-Semibold.ttf", "OpenSansSemibold");
            });

        builder.Services.AddShinyStores();

        // TODO: remove with Shiny.Extensions.Serialization 6.0.2 - 6.0.1 cannot serialize nullable primitives
        // with a value once any context is registered, which breaks LogService's Guid?/DateTimeOffset? [Bind] stores
        builder.Services.AddJsonContext(AppJsonContext.Default);
        
        builder.Services.AddDocumentStore(opts =>
        {
            var dbPath = Path.Combine(FileSystem.AppDataDirectory, "app.db");
            opts.DatabaseProvider = new SqliteDatabaseProvider($"Data Source={dbPath}");
            opts.JsonSerializerOptions = AppJsonContext.Default.Options;
            opts.UseReflectionFallback = false;
        });

#if DEBUG
        builder.Logging.SetMinimumLevel(LogLevel.Trace);
        builder.Logging.AddDebug();
#endif
        builder.Services.AddSingleton(Battery.Default);
        builder.Services.AddSingleton(TimeProvider.System);
        builder.Services.AddGps<ShinyKmlRecorder.Delegates.MyGpsDelegate>();

        // OBD transports are built per connection in ObdManager - only the radio managers are registered here
        builder.Services.AddBluetoothLE();
#if ANDROID
        builder.Services.AddBluetooth(); // classic bluetooth (RFCOMM/SPP) - not available on iOS
#endif

        // this is source generated by Shiny.Extensions.DependencyInjection - simply add [Singleton], [Scoped], or [Transient] to your classes
        builder.Services.AddGeneratedServices();
        var app = builder.Build();

        return app;
    }
}
#endif


